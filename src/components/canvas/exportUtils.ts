/**
 * Convert a graph definition into a LangGraph Python code string.
 * Generates a StateGraph with typed nodes and conditional edges.
 */
export function graphToLangGraphPython(graph: AgentGraphDefinition): string {
  const SKIP = new Set(["start", "end", "sticky_note", "frame"]);
  const _Q = '"'; // Python double-quote character
  const lines: string[] = [];

  // File header
  lines.push('"""');
  lines.push("Auto-generated LangGraph agent graph.");
  lines.push("Generated by Agent Studio — https://agentstudio.dev");
  lines.push('"""');
  lines.push("");
  lines.push("from typing import TypedDict, Annotated, Any");
  lines.push("import asyncio");
  lines.push("import json");
  lines.push("from langgraph.graph import StateGraph, END");
  lines.push("from langgraph.graph.message import add_messages");
  lines.push("");
  lines.push("");
  lines.push("# ── State Schema ──");
  lines.push("class AgentState(TypedDict):");
  lines.push("    input: Any");
  lines.push("    results: dict[str, Any]");
  lines.push("    messages: Annotated[list, add_messages]");
  lines.push("");
  lines.push("");
  lines.push("# ── Node Functions ──");

  for (const node of graph.nodes) {
    if (SKIP.has(node.type)) continue;
    const funcName = node.id.replace(/[^a-zA-Z0-9_]/g, "_");
    const prompt = node.data.prompt ?? "";
    const nodeId = node.id;
    const label = node.data.label;

    lines.push("async def " + funcName + "(state: AgentState) -> dict:");

    switch (node.type) {
      case "agent":
        lines.push('    """' + label + ": LLM agent node\"\"\"");
        lines.push("    # LLM call — replace with your provider (OpenAI, Anthropic, etc.)");
        lines.push("    import openai");
        lines.push("    client = openai.AsyncOpenAI()");
        lines.push("    response = await client.chat.completions.create(");
        lines.push('        model="gpt-4o-mini",');
        lines.push("        messages=[");
        lines.push('            {"role": "system", "content": ' + JSON.stringify(prompt.slice(0, 200)) + "},");
        lines.push('            {"role": "user", "content": json.dumps({"context": state.get("results", {}), "input": state.get("input", {})})},');
        lines.push("        ],");
        lines.push("        temperature=0.2,");
        lines.push("    )");
        lines.push("    output = response.choices[0].message.content");
        lines.push('    return {"results": {**state.get("results", {}), "' + nodeId + '": output}}');
        break;

      case "supervisor":
        lines.push('    """' + label + ': Supervisor router — LLM picks next step"""');
        lines.push("    import openai");
        lines.push("    client = openai.AsyncOpenAI()");
        const choices = JSON.stringify(
          graph.edges.filter((e) => e.source === node.id).map((e) => e.label || e.target)
        );
        lines.push("    choices = " + choices);
        lines.push("    response = await client.chat.completions.create(");
        lines.push('        model="gpt-4o-mini",');
        lines.push("        messages=[");
        lines.push('            {"role": "system", "content": f"Choose the next step from: {choices}. Respond with JSON: {\\\"next\\\": \\\"<choice>\\\"}"},');
        lines.push('            {"role": "user", "content": json.dumps(state.get("results", {}))},');
        lines.push("        ],");
        lines.push("        temperature=0.0,");
        lines.push("    )");
        lines.push("    parsed = json.loads(response.choices[0].message.content)");
        lines.push('    route = parsed.get("next", choices[0])');
        lines.push('    return {"results": {**state.get("results", {}), "' + nodeId + '": route}, "route": route}');
        break;

      case "tool":
        lines.push('    """Tool: ' + (node.data.toolName ?? "unknown") + " / " + (node.data.action ?? "") + '"""');
        lines.push("    # Tool execution — implement based on the tool type");
        lines.push("    tool_input = " + JSON.stringify(node.data.inputTemplate ?? {}) + "  # resolved at runtime");
        lines.push('    # Example: await execute_tool("' + (node.data.toolName ?? "tool") + '", tool_input)');
        lines.push('    output = {"action": "' + (node.data.action ?? "run") + '", "input": tool_input, "result": "TODO: implement tool"}');
        lines.push('    return {"results": {**state.get("results", {}), "' + nodeId + '": output}}');
        break;

      case "router": {
        const mode = node.data.routerMode === "ai" ? "AI-based" : "condition: " + (node.data.condition ?? "");
        lines.push('    """Router: ' + mode + '"""');
        if (node.data.routerMode === "ai") {
          lines.push("    # AI router — delegate to LLM to pick a branch");
          lines.push('    route = state.get("route", "")  # set by supervisor or previous AI router');
        } else {
          lines.push("    # Deterministic condition: " + (node.data.condition ?? ""));
          lines.push('    results = state.get("results", {})');
          lines.push("    # Evaluate: " + (node.data.condition ?? "True"));
          lines.push('    route = "true"  # TODO: evaluate condition expression');
        }
        lines.push('    return {"results": {**state.get("results", {}), "' + nodeId + '": {"route": route}}, "route": route}');
        break;
      }

      case "approval":
        lines.push('    """HITL approval gate: ' + (node.data.approvalReason ?? "Review required") + '"""');
        lines.push("    # Human-in-the-loop: pause and wait for approval");
        lines.push("    # In production, integrate with your approval system");
        lines.push('    print("[APPROVAL REQUIRED] ' + (node.data.approvalReason ?? "Review needed") + '")');
        lines.push('    approval = input("Approve? (y/n): ")  # Replace with async approval flow');
        lines.push('    if approval.lower() != "y":');
        lines.push('        raise Exception("Approval rejected")');
        lines.push('    return {"results": {**state.get("results", {}), "' + nodeId + '": {"approved": True}}}');
        break;

      case "loop":
        lines.push('    """Loop controller: max ' + (node.data.maxIterations ?? 3) + ' iterations"""');
        lines.push('    counter = state.get("loop_counters", {}).get("' + nodeId + '", 0) + 1');
        lines.push("    max_iter = " + (node.data.maxIterations ?? 3));
        lines.push("    exit_loop = counter > max_iter");
        lines.push('    loop_counters = {**state.get("loop_counters", {}), "' + nodeId + '": counter}');
        lines.push('    route = "exit" if exit_loop else "body"');
        lines.push('    return {"results": {**state.get("results", {}), "' + nodeId + '": {"iteration": counter, "exited": exit_loop}}, "loop_counters": loop_counters, "route": route}');
        break;

      case "transform":
        lines.push('    """Transform: ' + (node.data.transformOp ?? "map") + " " + (node.data.transformExpr ?? "") + '"""');
        lines.push('    results = state.get("results", {})');
        lines.push("    # Get input from the previous node");
        lines.push("    input_data = list(results.values())[-1] if results else None");
        lines.push("    if isinstance(input_data, list):");
        if (node.data.transformOp === "map") {
          lines.push("        output = [item.get('" + (node.data.transformExpr ?? "name") + "') if isinstance(item, dict) else item for item in input_data]");
        } else if (node.data.transformOp === "filter") {
          lines.push("        output = [item for item in input_data if item]");
        } else if (node.data.transformOp === "flatten") {
          lines.push("        output = [x for sublist in input_data for x in (sublist if isinstance(sublist, list) else [sublist])]");
        } else if (node.data.transformOp === "sort") {
          lines.push("        output = sorted(input_data, key=lambda x: str(x))");
        } else if (node.data.transformOp === "dedupe") {
          lines.push("        seen = set(); output = [x for x in input_data if not (str(x) in seen or seen.add(str(x)))]");
        } else {
          lines.push("        output = input_data  # " + (node.data.transformOp ?? "map"));
        }
        lines.push("    else:");
        lines.push("        output = input_data");
        lines.push('    return {"results": {**state.get("results", {}), "' + nodeId + '": output}}');
        break;

      case "aggregate":
        lines.push('    """Aggregate: ' + (node.data.aggregateMode ?? "concat") + '"""');
        lines.push('    results = state.get("results", {})');
        lines.push('    branch_results = [v for k, v in results.items() if k != "' + nodeId + '"]');
        if (node.data.aggregateMode === "concat") {
          lines.push("    output = []");
          lines.push("    for r in branch_results:");
          lines.push("        if isinstance(r, list): output.extend(r)");
          lines.push("        else: output.append(r)");
        } else if (node.data.aggregateMode === "merge") {
          lines.push("    output = {}");
          lines.push("    for r in branch_results:");
          lines.push("        if isinstance(r, dict): output.update(r)");
        } else if (node.data.aggregateMode === "count") {
          lines.push('    output = {"count": len(branch_results), "items": branch_results}');
        } else if (node.data.aggregateMode === "first") {
          lines.push("    output = branch_results[0] if branch_results else None");
        } else {
          lines.push("    output = branch_results");
        }
        lines.push('    return {"results": {**state.get("results", {}), "' + nodeId + '": output}}');
        break;

      case "variable":
        lines.push('    """Variable: ' + (node.data.varOp ?? "get") + " " + (node.data.varName ?? "") + '"""');
        lines.push('    variables = state.get("variables", {})');
        if (node.data.varOp === "set") {
          lines.push('    variables["' + (node.data.varName ?? "var") + '"] = ' + JSON.stringify(node.data.varValue ?? null));
          lines.push('    return {"variables": variables}');
        } else {
          lines.push('    output = variables.get("' + (node.data.varName ?? "var") + '", None)');
          lines.push('    return {"results": {**state.get("results", {}), "' + nodeId + '": output}}');
        }
        break;

      case "output":
        lines.push('    """Output formatter"""');
        lines.push('    results = state.get("results", {})');
        if (node.data.outputFields && Object.keys(node.data.outputFields).length > 0) {
          lines.push("    # Field mapping output");
          lines.push("    output = {}");
          for (const [key, template] of Object.entries(node.data.outputFields)) {
            lines.push('    output["' + key + '"] = results  # TODO: resolve template ' + template);
          }
        } else {
          lines.push("    output = results");
        }
        lines.push('    return {"results": {**state.get("results", {}), "' + nodeId + '": output}}');
        break;

      case "http":
        lines.push('    """HTTP Request: ' + (node.data.httpMethod ?? "GET") + " " + (node.data.httpUrl ?? "") + '"""');
        lines.push("    import aiohttp");
        lines.push("    async with aiohttp.ClientSession() as session:");
        lines.push('        method = "' + (node.data.httpMethod ?? "GET") + '"');
        lines.push('        url = "' + (node.data.httpUrl ?? "") + '"');
        lines.push("        headers = " + JSON.stringify(node.data.httpHeaders ?? {}));
        lines.push("        body = " + JSON.stringify(node.data.httpBody ?? null));
        lines.push("        async with session.request(method, url, headers=headers, json=body) as resp:");
        lines.push('            output = await resp.json() if "json" in resp.content_type else await resp.text()');
        lines.push('    return {"results": {**state.get("results", {}), "' + nodeId + '": output}}');
        break;

      case "delay":
        lines.push('    """Delay: wait ' + (node.data.delayMs ?? 1000) + 'ms"""');
        lines.push("    await asyncio.sleep(" + ((node.data.delayMs ?? 1000) / 1000) + ")");
        lines.push("    return state");
        break;

      case "mcp_server":
        lines.push('    """MCP Server: ' + (node.data.mcpServerId ?? "unknown") + '"""');
        lines.push("    # MCP server connection — configure via MCP SDK");
        lines.push("    return state");
        break;

      case "mcp_tool":
        lines.push('    """MCP Tool: ' + (node.data.mcpToolName ?? "unknown") + " from " + (node.data.mcpToolServer ?? "unknown") + '"""');
        lines.push("    # MCP tool call — use the MCP SDK client");
        lines.push("    output = " + JSON.stringify({ mcp_tool: node.data.mcpToolName ?? "", server: node.data.mcpToolServer ?? "" }));
        lines.push('    return {"results": {**state.get("results", {}), "' + nodeId + '": output}}');
        break;

      case "skill":
        lines.push('    """Skill: ' + (node.data.skillId ?? "unknown") + '"""');
        lines.push("    # Sub-skill invocation — call the Agent Studio API");
        lines.push("    import aiohttp");
        lines.push("    async with aiohttp.ClientSession() as session:");
        lines.push('        async with session.post("YOUR_API_URL/api/executions", json={"skillVersionId": "' + (node.data.skillId ?? "") + '", "inputData": state.get("input", {})}) as resp:');
        lines.push("            output = await resp.json()");
        lines.push('    return {"results": {**state.get("results", {}), "' + nodeId + '": output}}');
        break;

      default:
        lines.push('    """' + label + '"""');
        lines.push("    return state");
    }
    lines.push("");
  }

  // Build the graph
  lines.push("# ── Graph Construction ──");
  lines.push("graph = StateGraph(AgentState)");

  for (const node of graph.nodes) {
    if (SKIP.has(node.type)) continue;
    const funcName = node.id.replace(/[^a-zA-Z0-9_]/g, "_");
    lines.push('graph.add_node("' + node.id + '", ' + funcName + ")");
  }

  // Entry point
  const startNode = graph.nodes.find((n) => n.type === "start");
  if (startNode) {
    const startEdges = graph.edges.filter((e) => e.source === startNode.id);
    for (const e of startEdges) {
      lines.push('graph.set_entry_point("' + e.target + '")');
    }
  }

  // Collect conditional sources (routers, supervisors, loops)
  const conditionalSources = new Set<string>();
  for (const edge of graph.edges) {
    const source = graph.nodes.find((n) => n.id === edge.source);
    const target = graph.nodes.find((n) => n.id === edge.target);
    if (!source || !target) continue;
    if (target.type === "end") {
      lines.push('graph.add_edge("' + edge.source + '", END)');
    } else if (source.type === "router" || source.type === "supervisor" || source.type === "loop") {
      conditionalSources.add(edge.source);
    } else {
      lines.push('graph.add_edge("' + edge.source + '", "' + edge.target + '")');
    }
  }

  // Add conditional edges
  for (const srcId of conditionalSources) {
    const outEdges = graph.edges.filter((e) => e.source === srcId);
    const mappingEntries: string[] = [];
    const endId = graph.nodes.find((n) => n.type === "end")?.id;
    for (const e of outEdges) {
      const label = e.label || "default";
      const target = e.target === endId ? "END" : e.target;
      mappingEntries.push('"' + label + '": "' + target + '"');
    }
    lines.push(
      'graph.add_conditional_edges("' + srcId + '", lambda s: s.get("route", ""), {' + mappingEntries.join(", ") + "})"
    );
  }

  lines.push("");
  lines.push("# Compile the graph");
  lines.push("app = graph.compile()");
  lines.push("");
  lines.push("# ── Run the graph ──");
  lines.push('if __name__ == "__main__":');
  lines.push('    result = asyncio.run(app.ainvoke({"input": {}, "results": {}}))');
  lines.push("    print(json.dumps(result, indent=2, default=str))");
  lines.push("");

  return lines.join("\n");
}

