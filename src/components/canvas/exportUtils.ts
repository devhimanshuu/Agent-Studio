/**
 * Export the canvas viewport as a high-resolution PNG using html-to-image.
 * Dynamically imports the library to avoid SSR issues.
 */
export async function exportCanvasAsPng(
  containerRef: HTMLElement,
  filename = "agent-graph.png"
): Promise<void> {
  const { toPng } = await import("html-to-image");
  const dataUrl = await toPng(containerRef, {
    quality: 1.0,
    pixelRatio: 3,
    backgroundColor: "#07070d",
    style: { transform: "scale(1)", transformOrigin: "top left" },
  });
  downloadDataUrl(dataUrl, filename);
}

/**
 * Export the canvas viewport as an SVG.
 */
export async function exportCanvasAsSvg(
  containerRef: HTMLElement,
  filename = "agent-graph.svg"
): Promise<void> {
  const { toSvg } = await import("html-to-image");
  const dataUrl = await toSvg(containerRef, {
    backgroundColor: "#07070d",
  });
  downloadDataUrl(dataUrl, filename);
}

/**
 * Export the canvas viewport as a PDF using jsPDF + html-to-image.
 */
export async function exportCanvasAsPdf(
  containerRef: HTMLElement,
  filename = "agent-graph.pdf"
): Promise<void> {
  const [{ toPng }, { jsPDF }] = await Promise.all([
    import("html-to-image"),
    import("jspdf"),
  ]);
  const dataUrl = await toPng(containerRef, {
    quality: 1.0,
    pixelRatio: 2,
    backgroundColor: "#07070d",
  });
  const img = new Image();
  img.src = dataUrl;
  await new Promise<void>((resolve) => {
    img.onload = () => resolve();
  });
  const pdf = new jsPDF({
    orientation: img.width > img.height ? "landscape" : "portrait",
    unit: "px",
    format: [img.width, img.height],
  });
  pdf.addImage(dataUrl, "PNG", 0, 0, img.width, img.height);
  pdf.save(filename);
}

