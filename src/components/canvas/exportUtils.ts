/**
 * Convert a graph definition into a LangGraph TypeScript code string.
 */
export function graphToLangGraphTS(graph: AgentGraphDefinition): string {
  const SKIP = new Set(["start", "end", "sticky_note", "frame"]);
  const lines: string[] = [];

  lines.push("/**");
  lines.push(" * Auto-generated LangGraph agent graph.");
  lines.push(" * Generated by Agent Studio — https://agentstudio.dev");
  lines.push(" */");
  lines.push("");
  lines.push('import { StateGraph, Annotation, END } from "@langchain/langgraph";');
  lines.push('import { ChatOpenAI } from "@langchain/openai";');
  lines.push("");
  lines.push('const llm = new ChatOpenAI({ model: "gpt-4o-mini", temperature: 0.2 });');
  lines.push("");
  lines.push("");
  lines.push("// ── State Annotation ──");
  lines.push("const AgentState = Annotation.Root({");
  lines.push("  input: Annotation<Record<string, any>>");
  lines.push("  results: Annotation<Record<string, any>>({");
  lines.push('    reducer: (prev, curr) => ({ ...prev, ...curr }),');
  lines.push('    default: () => ({}),');
  lines.push("  }),");
  lines.push("  route: Annotation<string>");
  lines.push("});");
  lines.push("");
  lines.push("");
  lines.push("// ── Node Functions ──");

  for (const node of graph.nodes) {
    if (SKIP.has(node.type)) continue;
    const funcName = node.id.replace(/[^a-zA-Z0-9_]/g, "_");
    const prompt = node.data.prompt ?? "";
    const nodeId = node.id;
    const label = node.data.label;

    lines.push("async function " + funcName + "(state: typeof AgentState.State) {");

    switch (node.type) {
      case "agent":
        lines.push("  // " + label + ": LLM agent");
        lines.push("  const response = await llm.invoke([");
        lines.push("    { role: \"system\", content: " + JSON.stringify(prompt.slice(0, 200)) + " },");
        lines.push("    { role: \"user\", content: JSON.stringify({ context: state.results, input: state.input }) },");
        lines.push("  ]);");
        lines.push("  return { results: { ...state.results, \"" + nodeId + "\": response.content } };");
        break;

      case "supervisor": {
        const choices = JSON.stringify(
          graph.edges.filter((e) => e.source === node.id).map((e) => e.label || e.target)
        );
        lines.push("  // " + label + ": Supervisor router");
        lines.push("  const choices = " + choices + ";");
        lines.push("  const response = await llm.invoke([");
        lines.push("    { role: \"system\", content: `Choose the next step from: ${choices.join(\", \")}. Respond with JSON: {\"next\": \"<choice>\"}` },");
        lines.push("    { role: \"user\", content: JSON.stringify(state.results) },");
        lines.push("  ]);");
        lines.push("  const parsed = JSON.parse(response.content as string);");
        lines.push("  const route = parsed.next ?? choices[0];");
        lines.push("  return { results: { ...state.results, \"" + nodeId + "\": route }, route };");
        break;
      }

      case "tool":
        lines.push("  // " + label + ": Tool " + (node.data.toolName ?? "unknown"));
        lines.push("  const toolInput = " + JSON.stringify(node.data.inputTemplate ?? {}) + ";");
        lines.push("  // TODO: wire up your tool execution layer");
        lines.push("  const output = { action: \"" + (node.data.action ?? "run") + "\", input: toolInput };");
        lines.push("  return { results: { ...state.results, \"" + nodeId + "\": output } };");
        break;

      case "router":
        lines.push("  // " + label + ": Router");
        if (node.data.routerMode === "ai") {
          lines.push("  const route = state.route ?? \"\";");
        } else {
          lines.push("  // Condition: " + (node.data.condition ?? ""));
          lines.push("  const route = \"true\"; // TODO: evaluate condition");
        }
        lines.push("  return { results: { ...state.results, \"" + nodeId + "\": { route } }, route };");
        break;

      case "approval":
        lines.push("  // " + label + ": HITL approval");
        lines.push("  console.log(\"[APPROVAL REQUIRED] " + (node.data.approvalReason ?? "Review needed") + "\");");
        lines.push("  // TODO: integrate with your approval system");
        lines.push("  return { results: { ...state.results, \"" + nodeId + "\": { approved: true } } };");
        break;

      case "loop":
        lines.push("  // " + label + ": Loop (max " + (node.data.maxIterations ?? 3) + ")");
        lines.push("  const counter = (state.loopCounters?.[\"" + nodeId + "\"] ?? 0) + 1;");
        lines.push("  const exited = counter > " + (node.data.maxIterations ?? 3) + ";");
        lines.push("  const route = exited ? \"exit\" : \"body\";");
        lines.push("  return { results: { ...state.results, \"" + nodeId + "\": { iteration: counter, exited } }, route, loopCounters: { ...state.loopCounters, \"" + nodeId + "\": counter } };");
        break;

      case "transform":
        lines.push("  // " + label + ": Transform (" + (node.data.transformOp ?? "map") + ")");
        lines.push("  const input = Object.values(state.results).pop();");
        lines.push("  const output = Array.isArray(input) ? input : [input];");
        lines.push("  return { results: { ...state.results, \"" + nodeId + "\": output } };");
        break;

      case "aggregate":
        lines.push("  // " + label + ": Aggregate (" + (node.data.aggregateMode ?? "concat") + ")");
        lines.push("  const values = Object.values(state.results);");
        lines.push("  const output = values.flat();");
        lines.push("  return { results: { ...state.results, \"" + nodeId + "\": output } };");
        break;

      case "variable":
        lines.push("  // " + label + ": Variable " + (node.data.varOp ?? "get") + " " + (node.data.varName ?? ""));
        if (node.data.varOp === "set") {
          lines.push("  const variables = { ...state.variables, \"" + (node.data.varName ?? "var") + "\": " + JSON.stringify(node.data.varValue ?? null) + " };");
          lines.push("  return { variables };");
        } else {
          lines.push("  const output = state.variables?.[\"" + (node.data.varName ?? "var") + "\"] ?? null;");
          lines.push("  return { results: { ...state.results, \"" + nodeId + "\": output } };");
        }
        break;

      case "output":
        lines.push("  // " + label + ": Output formatter");
        lines.push("  return { results: { ...state.results, \"" + nodeId + "\": state.results } };");
        break;

      case "http":
        lines.push("  // " + label + ": HTTP " + (node.data.httpMethod ?? "GET") + " " + (node.data.httpUrl ?? ""));
        lines.push("  const resp = await fetch(\"" + (node.data.httpUrl ?? "") + "\", {");
        lines.push("    method: \"" + (node.data.httpMethod ?? "GET") + "\",");
        lines.push("    headers: " + JSON.stringify(node.data.httpHeaders ?? {}) + ",");
        if (node.data.httpBody) {
          lines.push("    body: JSON.stringify(" + JSON.stringify(node.data.httpBody) + "),");
        }
        lines.push("  });");
        lines.push("  const output = await resp.json();");
        lines.push("  return { results: { ...state.results, \"" + nodeId + "\": output } };");
        break;

      case "delay":
        lines.push("  // " + label + ": Delay " + (node.data.delayMs ?? 1000) + "ms");
        lines.push("  await new Promise(r => setTimeout(r, " + (node.data.delayMs ?? 1000) + "));");
        lines.push("  return state;");
        break;

      case "mcp_server":
        lines.push("  // " + label + ": MCP Server " + (node.data.mcpServerId ?? ""));
        lines.push("  return state;");
        break;

      case "mcp_tool":
        lines.push("  // " + label + ": MCP Tool " + (node.data.mcpToolName ?? ""));
        lines.push("  const output = { mcpTool: \"" + (node.data.mcpToolName ?? "") + "\", server: \"" + (node.data.mcpToolServer ?? "") + "\" };");
        lines.push("  return { results: { ...state.results, \"" + nodeId + "\": output } };");
        break;

      case "skill":
        lines.push("  // " + label + ": Skill invocation");
        lines.push("  const resp = await fetch(\"YOUR_API_URL/api/executions\", {");
        lines.push("    method: \"POST\",");
        lines.push("    headers: { \"Content-Type\": \"application/json\" },");
        lines.push("    body: JSON.stringify({ skillVersionId: \"" + (node.data.skillId ?? "") + "\", inputData: state.input }),");
        lines.push("  });");
        lines.push("  const output = await resp.json();");
        lines.push("  return { results: { ...state.results, \"" + nodeId + "\": output } };");
        break;

      default:
        lines.push("  // " + label);
        lines.push("  return state;");
    }
    lines.push("}");
    lines.push("");
  }

  lines.push("// ── Graph Construction ──");
  lines.push("const graph = new StateGraph(AgentState)");

  for (const node of graph.nodes) {
    if (SKIP.has(node.type)) continue;
    const funcName = node.id.replace(/[^a-zA-Z0-9_]/g, "_");
    lines.push('  .addNode("' + node.id + '", ' + funcName + ")");
  }

  const startTarget = graph.edges.find((e) => e.source === startNodeId(graph))?.target ?? "END";
  lines.push("  .addEdge('__start__', '" + startTarget + "')");

  // Collect conditional sources
  const conditionalSources = new Set<string>();
  for (const edge of graph.edges) {
    const source = graph.nodes.find((n) => n.id === edge.source);
    if (!source || source.type === "start") continue;
    const target = graph.nodes.find((n) => n.id === edge.target);
    if (!target) continue;
    if (target.type === "end") {
      lines.push('  .addEdge("' + edge.source + '", END)');
    } else if (source.type === "router" || source.type === "supervisor" || source.type === "loop") {
      conditionalSources.add(edge.source);
    } else {
      lines.push('  .addEdge("' + edge.source + '", "' + edge.target + '")');
    }
  }

  // Conditional edges
  for (const srcId of conditionalSources) {
    const outEdges = graph.edges.filter((e) => e.source === srcId);
    const mappingEntries: string[] = [];
    const endId = graph.nodes.find((n) => n.type === "end")?.id;
    for (const e of outEdges) {
      const label = e.label || "default";
      const target = e.target === endId ? "__end__" : e.target;
      mappingEntries.push('"' + label + '": "' + target + '"');
    }
    lines.push('  .addConditionalEdges("' + srcId + '", (state) => state.route ?? "", {' + mappingEntries.join(", ") + "})");
  }

  lines.push("  .compile();");
  lines.push("");
  lines.push("export default app;");
  lines.push("");
  lines.push("// ── Run ──");
  lines.push("// const result = await app.invoke({ input: {}, results: {} });");
  lines.push("// console.log(result);");
  lines.push("");

  return lines.join("\n");
}

function startNodeId(graph: AgentGraphDefinition): string {
  return graph.nodes.find((n) => n.type === "start")?.id ?? "";
}

// ─── JSON Import/Export (already exists, but add a typed wrapper) ───

export function exportGraphAsJson(graph: AgentGraphDefinition): string {
  return JSON.stringify(graph, null, 2);
}

export function importGraphFromJson(jsonStr: string): AgentGraphDefinition | null {
  try {
    const data = JSON.parse(jsonStr);
    if (data && data.version === 1 && Array.isArray(data.nodes) && Array.isArray(data.edges)) {
      return data as AgentGraphDefinition;
    }
    return null;
  } catch {
    return null;
  }
}

