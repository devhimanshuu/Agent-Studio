/**
 * Convert a graph definition into a Mermaid.js flowchart diagram string.
 * Uses `graph LR` (left-to-right) direction.
 */
export function graphToMermaid(graph: AgentGraphDefinition): string {
  const lines: string[] = ["graph LR"];

  const nodeLabels = graph.nodes.map((n) => {
    const id = n.id.replace(/[^a-zA-Z0-9_]/g, "_");
    const label = n.data.label || n.id;
    switch (n.type) {
      case "start":
        return `  ${id}([🟢 ${label}])`;
      case "end":
        return `  ${id}([🔴 ${label}])`;
      case "agent":
        return `  ${id}["🤖 ${label}"]`;
      case "supervisor":
        return `  ${id}{"🔀 ${label}"}`;
      case "tool":
        return `  ${id}["🔧 ${label}"]`;
      case "router":
        return `  ${id}{"❓ ${label}"}`;
      case "approval":
        return `  ${id}["🛡️ ${label}"]`;
      case "loop":
        return `  ${id}{"🔁 ${label}"}`;
      case "parallel":
        return `  ${id}{"⚡ ${label}"}`;
      case "subgraph":
        return `  ${id}["📦 ${label}"]`;
      case "sticky_note":
        return `  ${id}["📝 ${label}"]:::note`;
      case "frame":
        return `  ${id}["📐 ${label}"]:::frame`;
      default:
        return `  ${id}["${label}"]`;
    }
  });

  lines.push(...nodeLabels);

  // Edges
  const edgeLines = graph.edges.map((e) => {
    const src = e.source.replace(/[^a-zA-Z0-9_]/g, "_");
    const tgt = e.target.replace(/[^a-zA-Z0-9_]/g, "_");
    if (e.label) {
      return `  ${src} -->|"${e.label}"| ${tgt}`;
    }
    return `  ${src} --> ${tgt}`;
  });

  lines.push("");
  lines.push(...edgeLines);

  // Class definitions
  lines.push("");
  lines.push("  classDef note fill:#fef3c7,stroke:#f59e0b,stroke-width:1px,color:#92400e");
  lines.push("  classDef frame fill:#e0e7ff,stroke:#6366f1,stroke-width:1px,color:#3730a3");

  return lines.join("\n");
}

// ─── LangGraph (Python) Export ───

/**
 * Convert a graph definition into a LangGraph Python code string.
 * Generates a StateGraph with typed nodes and conditional edges.
 */
export function graphToLangGraphPython(graph: AgentGraphDefinition): string {
  const lines: string[] = [
    '"""',
    "Auto-generated LangGraph agent graph.",
    "Generated by Agent Studio — https://agentstudio.dev",
    '"""',
    "",
    "from typing import TypedDict, Annotated, Any",
    "from langgraph.graph import StateGraph, END",
    "from langgraph.graph.message import add_messages",
    "",
    "",
    "# ── State Schema ──",
    "class AgentState(TypedDict):",
    "    input: Any",
    "    results: dict[str, Any]",
    "    messages: Annotated[list, add_messages]",
    "",
    "",
    "# ── Node Functions ──",
  ];

  for (const node of graph.nodes) {
    if (node.type === "start" || node.type === "end" || node.type === "sticky_note" || node.type === "frame") continue;
    const funcName = node.id.replace(/[^a-zA-Z0-9_]/g, "_");
    const prompt = node.data.prompt ?? "";
    lines.push(`async def ${funcName}(state: AgentState) -> dict:`);
    if (node.type === "agent" || node.type === "supervisor") {
      lines.push(`    """${node.data.label}: ${prompt.slice(0, 100)}"""`);
      lines.push(`    # TODO: Implement LLM call`);
      lines.push(`    return {"results": {**state.get("results", {}), "${node.id}": {}}}`);
    } else if (node.type === "tool") {
      lines.push(`    """Tool: ${node.data.toolName ?? "unknown"} / ${node.data.action ?? ""}"""`);
      lines.push(`    # TODO: Implement tool call`);
      lines.push(`    return {"results": {**state.get("results", {}), "${node.id}": {}}}`);
    } else if (node.type === "router") {
      lines.push(`    """Router: ${node.data.routerMode === "ai" ? "AI-based" : `condition: ${node.data.condition ?? ""}`}"""`);
      lines.push(`    return state`);
    } else if (node.type === "approval") {
      lines.push(`    """Approval gate: ${node.data.approvalReason ?? ""}"""`);
      lines.push(`    # TODO: Implement HITL approval`);
      lines.push(`    return state`);
    } else if (node.type === "loop") {
      lines.push(`    """Loop: max ${node.data.maxIterations ?? 3} iterations"""`);
      lines.push(`    return state`);
    } else if (node.type === "transform") {
      lines.push(`    """Transform: ${node.data.transformOp ?? "map"} ${node.data.transformExpr ?? ""}"""`);
      lines.push(`    return state`);
    } else if (node.type === "aggregate") {
      lines.push(`    """Aggregate: ${node.data.aggregateMode ?? "concat"}"""`);
      lines.push(`    return state`);
    } else {
      lines.push(`    """${node.data.label}"""`);
      lines.push(`    return state`);
    }
    lines.push("");
  }

  // Build the graph
  lines.push("# ── Graph Construction ──");
  lines.push("graph = StateGraph(AgentState)");

  for (const node of graph.nodes) {
    if (node.type === "start" || node.type === "end" || node.type === "sticky_note" || node.type === "frame") continue;
    const funcName = node.id.replace(/[^a-zA-Z0-9_]/g, "_");
    lines.push(`graph.add_node("${node.id}", ${funcName})`);
  }

  // Entry point
  const startNode = graph.nodes.find((n) => n.type === "start");
  if (startNode) {
    // Connect start to its targets
    const startEdges = graph.edges.filter((e) => e.source === startNode.id);
    for (const e of startEdges) {
      lines.push(`graph.set_entry_point("${e.target}")`);
    }
  }

  // Edges
  for (const edge of graph.edges) {
    const source = graph.nodes.find((n) => n.id === edge.source);
    const target = graph.nodes.find((n) => n.id === edge.target);
    if (!source || !target) continue;
    if (target.type === "end") {
      lines.push(`graph.add_edge("${edge.source}", END)`);
    } else if (source.type === "router" || source.type === "supervisor") {
      if (edge.label) {
        lines.push(`graph.add_conditional_edges("${edge.source}", lambda s: s.get("route", ""), {"${edge.label}": "${edge.target}"})`);
      }
    } else {
      lines.push(`graph.add_edge("${edge.source}", "${edge.target}")`);
    }
  }

  lines.push("");
  lines.push("# Compile the graph");
  lines.push("app = graph.compile()");
  lines.push("");

  return lines.join("\n");
}

