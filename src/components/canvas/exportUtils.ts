/**
 * Convert a graph definition into a LangGraph TypeScript code string.
 */
export function graphToLangGraphTS(graph: AgentGraphDefinition): string {
  const lines: string[] = [
    "/**",
    " * Auto-generated LangGraph agent graph.",
    " * Generated by Agent Studio — https://agentstudio.dev",
    " */",
    "",
    'import { StateGraph, Annotation, END } from "@langchain/langgraph";',
    "",
    "",
    "// ── State Annotation ──",
    "const AgentState = Annotation.Root({",
    "  input: Annotation<string>,",
    "  results: Annotation<Record<string, any>>({",
    '    reducer: (prev, curr) => ({ ...prev, ...curr }),',
    '    default: () => ({}),',
    "  }),",
    "});",
    "",
    "",
    "// ── Node Functions ──",
  ];

  for (const node of graph.nodes) {
    if (node.type === "start" || node.type === "end" || node.type === "sticky_note" || node.type === "frame") continue;
    const funcName = node.id.replace(/[^a-zA-Z0-9_]/g, "_");
    lines.push(`async function ${funcName}(state: typeof AgentState.State) {`);
    lines.push(`  // ${node.data.label}`);
    lines.push(`  return state.results;`);
    lines.push(`}`);
    lines.push("");
  }

  lines.push("// ── Graph Construction ──");
  lines.push("const graph = new StateGraph(AgentState)");

  for (const node of graph.nodes) {
    if (node.type === "start" || node.type === "end" || node.type === "sticky_note" || node.type === "frame") continue;
    const funcName = node.id.replace(/[^a-zA-Z0-9_]/g, "_");
    lines.push(`  .addNode("${node.id}", ${funcName})`);
  }

  lines.push("  .addEdge('__start__', '" + (graph.edges.find((e) => e.source === startNodeId(graph))?.target ?? "END") + "')");

  for (const edge of graph.edges) {
    const source = graph.nodes.find((n) => n.id === edge.source);
    if (!source || source.type === "start") continue;
    const target = graph.nodes.find((n) => n.id === edge.target);
    if (!target) continue;
    if (target.type === "end") {
      lines.push(`  .addEdge("${edge.source}", END)`);
    } else if (source.type === "router" && edge.label) {
      // Router conditional edges handled separately
    } else {
      lines.push(`  .addEdge("${edge.source}", "${edge.target}")`);
    }
  }

  lines.push("  .compile();");
  lines.push("");
  lines.push("export default app;");

  return lines.join("\n");
}

function startNodeId(graph: AgentGraphDefinition): string {
  return graph.nodes.find((n) => n.type === "start")?.id ?? "";
}

// ─── JSON Import/Export (already exists, but add a typed wrapper) ───

export function exportGraphAsJson(graph: AgentGraphDefinition): string {
  return JSON.stringify(graph, null, 2);
}

export function importGraphFromJson(jsonStr: string): AgentGraphDefinition | null {
  try {
    const data = JSON.parse(jsonStr);
    if (data && data.version === 1 && Array.isArray(data.nodes) && Array.isArray(data.edges)) {
      return data as AgentGraphDefinition;
    }
    return null;
  } catch {
    return null;
  }
}

